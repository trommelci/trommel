import { readFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

import { modelProblem } from '../../src/lockfile/model.ts';
import type { ModelEntry, Ref, ResolvedModel } from '../../src/lockfile/model.ts';
import type { Unparseable } from '../../src/lockfile/npm.ts';
import { parseYarnClassicLockfile } from '../../src/lockfile/yarn-classic.ts';
import type { ClassicWorkspace } from '../../src/lockfile/yarn-classic.ts';

const FIXTURE = readFileSync(new URL('../fixtures/lockfile/yarn-classic.lock', import.meta.url), 'utf8');
const HEADER = '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n';

const WORKSPACE: ClassicWorkspace = {
  importers: new Map([
    [
      '',
      new Map([
        ['acorn', '^8.14.0'],
        ['@ampproject/remapping', '^2.2.0'],
        ['my-lib', '^1.0.0'],
        ['ghost', '^9.0.0'],
      ]),
    ],
    ['packages/lib', new Map([['acorn', '^8.11.0']])],
  ]),
  packages: new Map([['my-lib', 'packages/lib']]),
};
const NO_WORKSPACE: ClassicWorkspace = { importers: new Map(), packages: new Map() };

function read(text: string, workspace: ClassicWorkspace = WORKSPACE): ResolvedModel {
  const result = parseYarnClassicLockfile(text, workspace);
  if ('kind' in result) {
    throw new Error(`expected a model, got: ${result.reason}`);
  }
  return result;
}

function refuse(text: string): Unparseable {
  const result = parseYarnClassicLockfile(text, WORKSPACE);
  if (!('kind' in result)) {
    throw new Error('expected a refusal, got a model');
  }
  return result;
}

const entryOf = (model: ResolvedModel, id: string): ModelEntry => {
  const found = model.entries.get(id);
  if (found === undefined) {
    throw new Error(`no entry ${id}`);
  }
  return found;
};
const importerOf = (model: ResolvedModel, dir: string): ReadonlyMap<string, Ref> => {
  const found = model.importers.get(dir);
  if (found === undefined) {
    throw new Error(`no importer ${dir}`);
  }
  return found;
};

describe('parseYarnClassicLockfile', () => {
  it('reads the fixture into a model that passes modelProblem', () => {
    const model = read(FIXTURE);
    expect(modelProblem(model)).toBeNull();
    expect(model.env).toBeNull();
    expect([...model.entries.keys()].sort()).toEqual([
      '@ampproject/remapping@2.3.0',
      '@jridgewell/gen-mapping@0.3.5',
      '@jridgewell/trace-mapping@0.3.25',
      'acorn@8.14.0',
      'fsevents@2.3.3',
      'local-tool@1.0.0',
    ]);
    expect(entryOf(model, '@ampproject/remapping@2.3.0').name).toBe('@ampproject/remapping');
  });

  it('importers come from the declarations it is given', () => {
    const model = read(FIXTURE);
    expect([...model.importers.keys()]).toEqual(['', 'packages/lib']);
    const root = importerOf(model, '');
    expect([...root.keys()]).toEqual(['acorn', '@ampproject/remapping', 'my-lib', 'ghost']);
    expect(root.get('acorn')).toEqual({ kind: 'entry', id: 'acorn@8.14.0' });
    expect(importerOf(model, 'packages/lib').get('acorn')).toEqual({ kind: 'entry', id: 'acorn@8.14.0' });
    expect(read(HEADER, NO_WORKSPACE).importers.size).toBe(0);
  });

  it('each descriptor of an entry resolves to it', () => {
    const model = read(FIXTURE);
    const root = importerOf(model, '');
    expect(root.get('@ampproject/remapping')).toEqual({ kind: 'entry', id: '@ampproject/remapping@2.3.0' });
    const lib = importerOf(model, 'packages/lib');
    expect(lib.get('acorn')).toEqual(root.get('acorn'));
    const other = read(FIXTURE, { importers: new Map([['', new Map([['@ampproject/remapping', '^2.3.0']])]]), packages: new Map() });
    expect(importerOf(other, '').get('@ampproject/remapping')).toEqual({ kind: 'entry', id: '@ampproject/remapping@2.3.0' });
  });

  it('reads dependencies and optionalDependencies, with quoted names', () => {
    const model = read(FIXTURE);
    expect(entryOf(model, '@ampproject/remapping@2.3.0').dependencies).toEqual(
      new Map([
        ['@jridgewell/gen-mapping', { kind: 'entry', id: '@jridgewell/gen-mapping@0.3.5' }],
        ['@jridgewell/trace-mapping', { kind: 'entry', id: '@jridgewell/trace-mapping@0.3.25' }],
      ]),
    );
    expect(entryOf(model, 'local-tool@1.0.0').dependencies).toEqual(
      new Map([
        ['acorn', { kind: 'entry', id: 'acorn@8.14.0' }],
        ['fsevents', { kind: 'entry', id: 'fsevents@2.3.3' }],
        ['@jridgewell/gen-mapping', { kind: 'entry', id: '@jridgewell/gen-mapping@0.3.5' }],
      ]),
    );
    expect(entryOf(model, 'acorn@8.14.0').peers).toEqual([]);
  });

  it('integrity is the content, resolved when there is none', () => {
    const model = read(FIXTURE);
    expect(entryOf(model, 'acorn@8.14.0').content).toEqual({
      integrity: 'sha512-cl669nCJTZBsL97OF4kR6BEk4wV2rqk35SOV91fADGPpf01Ng0NCrxZ5nk4UmNMwIEeQ35JpoSXZ2nPj5RsSY5w==',
    });
    expect(entryOf(model, 'local-tool@1.0.0').content).toEqual({ resolved: 'file:./vendor/local-tool' });
  });

  it('a workspace package declared by range is a link', () => {
    const model = read(FIXTURE);
    expect(importerOf(model, '').get('my-lib')).toEqual({ kind: 'link', dir: 'packages/lib' });
  });

  it('a declared range with no entry that is no workspace package is unresolved', () => {
    const model = read(FIXTURE);
    expect(importerOf(model, '').get('ghost')).toEqual({ kind: 'unresolved' });
    const stale = read(FIXTURE, { importers: new Map([['', new Map([['acorn', '^1.0.0']])]]), packages: new Map() });
    expect(importerOf(stale, '').get('acorn')).toEqual({ kind: 'unresolved' });
  });

  it('a dependency resolves like a declaration: entry, else link, else unresolved', () => {
    const text = `${HEADER}a@^1.0.0:\n  version "1.0.0"\n  resolved "https://x/a"\n  dependencies:\n    b "^2.0.0"\n    my-lib "^1.0.0"\n    c "^3.0.0"\n\nb@^2.0.0:\n  version "2.0.0"\n  resolved "https://x/b"\n`;
    const a = entryOf(read(text), 'a@1.0.0');
    expect(a.dependencies.get('b')).toEqual({ kind: 'entry', id: 'b@2.0.0' });
    expect(a.dependencies.get('my-lib')).toEqual({ kind: 'link', dir: 'packages/lib' });
    expect(a.dependencies.get('c')).toEqual({ kind: 'unresolved' });
  });

  it('a lockfile with only its header is an empty model', () => {
    const model = read(HEADER, NO_WORKSPACE);
    expect(model.entries.size).toBe(0);
    expect(model.importers.size).toBe(0);
    expect(model.env).toBeNull();
    expect(modelProblem(model)).toBeNull();
  });

  it('strips a byte order mark and carriage returns', () => {
    const crlf = `\uFEFF${FIXTURE.replace(/\n/g, '\r\n')}`;
    expect(read(crlf)).toEqual(read(FIXTURE));
  });

  it('reads past a field it does not use', () => {
    const text = `${HEADER}a@^1.0.0:\n  version "1.0.0"\n  uid abc123\n  resolved "https://x/a"\n`;
    expect(entryOf(read(text), 'a@1.0.0').content).toEqual({ resolved: 'https://x/a' });
  });

  describe('a name in both dependencies and optionalDependencies', () => {
    const both = (optional: string): string =>
      `${HEADER}a@^1.0.0:\n  version "1.0.0"\n  resolved "https://x/a"\n  dependencies:\n    b "^2.0.0"\n  optionalDependencies:\n    b "${optional}"\n\n` +
      `b@^2.0.0, b@~2.0.0:\n  version "2.0.0"\n  resolved "https://x/b"\n\nb@^3.0.0:\n  version "3.0.0"\n  resolved "https://x/b3"\n`;

    it('is one reference when both fields resolve it the same', () => {
      expect(entryOf(read(both('^2.0.0')), 'a@1.0.0').dependencies).toEqual(new Map([['b', { kind: 'entry', id: 'b@2.0.0' }]]));
      expect(entryOf(read(both('~2.0.0')), 'a@1.0.0').dependencies.get('b')).toEqual({ kind: 'entry', id: 'b@2.0.0' });
    });

    it('is refused when the fields resolve it to different references', () => {
      expect(refuse(both('^3.0.0')).reason).toMatch(/"b".*twice/);
      expect(refuse(both('^9.0.0')).reason).toMatch(/"b".*twice/);
    });

    it('is still refused when one block lists it twice', () => {
      const text = `${HEADER}a@^1.0.0:\n  version "1.0.0"\n  resolved "https://x/a"\n  dependencies:\n    b "^2.0.0"\n    b "^2.0.0"\n`;
      expect(refuse(text).reason).toMatch(/line \d+/);
    });
  });

  it('an importer directory the model cannot hold is refused by modelProblem', () => {
    const result = parseYarnClassicLockfile(HEADER, { importers: new Map([['.', new Map()]]), packages: new Map() });
    expect(result).toMatchObject({ kind: 'unparseable', format: 'yarn' });
    expect((result as Unparseable).reason).toMatch(/importer directory/);
  });

  it('an id with @* is refused by modelProblem', () => {
    const text = `${HEADER}a@^1.0.0:\n  version "1.0.0@*"\n  resolved "https://x/a"\n`;
    expect(refuse(text).reason).toMatch(/@\*/);
  });

  const entry = (name: string, version: string, descriptors = `${name}@^${version}`): string =>
    `${descriptors}:\n  version "${version}"\n  resolved "https://x/${name}"\n`;

  it.each([
    ['no header', 'a@^1.0.0:\n  version "1.0.0"\n  resolved "https://x/a"\n', /yarn lockfile v1/],
    ['a header with another version', '# yarn lockfile v2\n\na@^1.0.0:\n  version "1.0.0"\n  resolved "https://x/a"\n', /yarn lockfile v1/],
    ['an empty text', '', /yarn lockfile v1/],
    ['a duplicate name@version', `${HEADER}${entry('a', '1.0.0')}\n${entry('a', '1.0.0', 'a@~1.0.0')}`, /duplicate/],
    ['a six-space line', `${HEADER}a@^1.0.0:\n  version "1.0.0"\n  resolved "https://x/a"\n  dependencies:\n      b "^1.0.0"\n`, /line \d+/],
    ['a field line at one space', `${HEADER}a@^1.0.0:\n version "1.0.0"\n`, /line \d+/],
    ['a tab-indented line', `${HEADER}a@^1.0.0:\n\tversion "1.0.0"\n`, /line \d+/],
    ['a four-space line outside a block', `${HEADER}a@^1.0.0:\n  version "1.0.0"\n  resolved "https://x/a"\n    b "^1.0.0"\n`, /line \d+/],
    ['a field before any entry', `${HEADER}  version "1.0.0"\n`, /line \d+/],
    ['a column-0 line that is no entry', `${HEADER}a@^1.0.0\n`, /line \d+/],
    ['an unterminated quote', `${HEADER}"a@^1.0.0:\n`, /line \d+/],
    ['a descriptor in two entries', `${HEADER}${entry('a', '1.0.0')}\n${entry('a', '1.1.0', 'a@^1.0.0')}`, /descriptor/],
    ['descriptors with two names', `${HEADER}${entry('a', '1.0.0', 'a@^1.0.0, b@^1.0.0')}`, /name/],
    ['a descriptor with no range', `${HEADER}${entry('a', '1.0.0', 'a')}`, /line \d+/],
    ['no version', `${HEADER}a@^1.0.0:\n  resolved "https://x/a"\n`, /version/],
    ['neither integrity nor resolved', `${HEADER}a@^1.0.0:\n  version "1.0.0"\n`, /integrity|resolved/],
    ['a field twice', `${HEADER}a@^1.0.0:\n  version "1.0.0"\n  version "1.0.1"\n  resolved "https://x/a"\n`, /twice|more than once|duplicate field/],
    ['an unknown block', `${HEADER}a@^1.0.0:\n  version "1.0.0"\n  resolved "https://x/a"\n  bin:\n    a "x"\n`, /line \d+/],
    ['a dependency line with no range', `${HEADER}a@^1.0.0:\n  version "1.0.0"\n  resolved "https://x/a"\n  dependencies:\n    b\n`, /line \d+/],
  ])('refuses %s', (_name, text, reason) => {
    const result = refuse(text);
    expect(result.format).toBe('yarn');
    expect(result.reason).toMatch(reason);
  });

  it('never throws on hostile bytes', () => {
    for (const text of ['\uFEFF', '\r\n\r\n', '"', '":', ':', '  ', '# yarn lockfile v1\n"\\u12":\n', `${HEADER}"a@^1\\":\n`]) {
      expect(() => parseYarnClassicLockfile(text, WORKSPACE)).not.toThrow();
    }
  });
});
